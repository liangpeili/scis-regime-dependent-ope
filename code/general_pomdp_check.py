#!/usr/bin/env python3
"""General sensor-POMDP validation for regime-dependent observation.

The environment is independent of the AMM simulator. A linear-Gaussian state is
controlled through normal, degraded, and outage observation regimes. The target
policy acts on the current belief, while the burn-in history is generated by a
different logging policy. Ground-truth target rollouts and model-based Monte
Carlo estimates use disjoint random streams; latent truth never enters either
estimator.

Output: results/general_pomdp_check.json (non-C1 experiment).
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import numpy as np

import trajectory_value_check as tvc

ROOT = Path(__file__).resolve().parents[1]
OUT_JSON = ROOT / "results" / "general_pomdp_check.json"

N_STEPS = 48
BURN_IN = 8
ALPHA = 0.1
A = 0.97
B = 0.35
SIGMA = 0.20
ACTION_GAIN = 0.70
ACTION_COST = 0.05
LOGGING_GAIN = 0.15
OBS_SD = 0.10
DEGRADED_PHI = 0.85
DEGRADED_SD = 0.35
OUTAGE_PHI = 0.90
OUTAGE_SD = 0.05
BRANCH_THRESHOLD = 0.65
REGIMES = ("normal", "degraded", "outage")
CAL_SEEDS = tuple(range(3000, 3128))
EVAL_SEEDS = tuple(range(4000, 4128))


def regime_at(t: int) -> str:
    if 16 <= t < 32:
        return "degraded"
    if 32 <= t < 40:
        return "outage"
    return "normal"


def conformal_q(scores: np.ndarray) -> float:
    return float(tvc.pvc.conformal_quantile(np.asarray(scores, dtype=float), ALPHA))


def prior_update_normal(mean: float, var: float, y: float) -> tuple[float, float]:
    gain = var / (var + OBS_SD**2)
    return mean + gain * (y - mean), (1.0 - gain) * var


def prior_predict(mean: float, var: float, action: float,
                  a: float = A, sigma: float = SIGMA) -> tuple[float, float]:
    return a * mean + B * action, a**2 * var + sigma**2


def fit_naive_dynamics(observations: np.ndarray, actions: np.ndarray) -> tuple[float, float]:
    previous = observations[:-1]
    current = observations[1:]
    control = actions[:-1]
    denominator = float(previous @ previous)
    a_hat = float(np.clip((previous @ (current - B * control)) / max(denominator, 1e-12), 0.80, 0.995))
    residual = current - a_hat * previous - B * control
    sigma_hat = max(float(np.sqrt(np.mean(residual**2))), 0.05)
    return a_hat, sigma_hat


def make_history(seed: int) -> dict:
    rng = np.random.default_rng([seed, 101])
    x = float(rng.normal())
    mean, var = 0.0, 1.0
    observations = []
    actions = []
    for _ in range(BURN_IN):
        y = x + rng.normal(0.0, OBS_SD)
        mean, var = prior_update_normal(mean, var, y)
        action = float(np.clip(-LOGGING_GAIN * y + rng.normal(0.0, 0.30), -1.0, 1.0))
        observations.append(float(y))
        actions.append(action)
        x = A * x + B * action + rng.normal(0.0, SIGMA)
        mean, var = prior_predict(mean, var, action)
    return {
        "x_start": x,
        "observations": np.asarray(observations),
        "actions": np.asarray(actions),
        "identified_prior": (mean, var),
        "naive_dynamics": fit_naive_dynamics(
            np.asarray(observations), np.asarray(actions)
        ),
        "predecision_group": int(observations[-1] > 0.0) + int(observations[-1] >= 1.0),
    }


def identified_belief_update(mean, cov, y, regime):
    if regime == "outage":
        return mean, cov
    if regime == "normal":
        mean = mean.copy()
        cov = cov.copy()
        mean[1] = 0.0
        cov[1, :] = 0.0
        cov[:, 1] = 0.0
        h = np.array([1.0, 0.0])
        r = OBS_SD**2
    else:
        h = np.array([1.0, 1.0])
        r = 0.0
    innovation = y - float(h @ mean)
    s = float(h @ cov @ h + r)
    gain = cov @ h / max(s, 1e-12)
    mean = mean + gain * innovation
    cov = cov - np.outer(gain, h @ cov)
    cov = 0.5 * (cov + cov.T)
    return mean, cov


def identified_belief_predict(mean, cov, action, next_regime):
    phi = DEGRADED_PHI if next_regime == "degraded" else 0.0
    q_b = DEGRADED_SD**2 if next_regime == "degraded" else 0.0
    f = np.array([[A, 0.0], [0.0, phi]])
    control = np.array([B * action, 0.0])
    q = np.diag([SIGMA**2, q_b])
    if next_regime in {"normal", "outage"}:
        f[1, 1] = 0.0
        q[1, 1] = 0.0
    return f @ mean + control, f @ cov @ f.T + q


def rollout_target(start_x: float, prior, rng,
                   dynamics: tuple[float, float] = (A, SIGMA)) -> dict:
    a_dyn, sigma_dyn = dynamics
    x = float(start_x)
    bias = 0.0
    eta = 0.0
    anchor = None
    previous_y = None
    mean = np.array([prior[0], 0.0], dtype=float)
    cov = np.diag([prior[1], 0.0])
    rewards = {r: [] for r in REGIMES}
    actions = []
    for t in range(BURN_IN, N_STEPS):
        regime = regime_at(t)
        if regime == "normal":
            bias = 0.0
            y = x + rng.normal(0.0, OBS_SD)
        elif regime == "degraded":
            bias = DEGRADED_PHI * bias + rng.normal(0.0, DEGRADED_SD)
            y = x + bias
        else:
            if anchor is None:
                anchor = previous_y
                eta = 0.0
            eta = OUTAGE_PHI * eta + rng.normal(0.0, OUTAGE_SD)
            y = anchor + eta
        mean, cov = identified_belief_update(mean, cov, y, regime)
        point = float(mean[0])
        action = float(np.clip(-ACTION_GAIN * point, -1.0, 1.0))
        actions.append(action)
        x = a_dyn * x + B * action + rng.normal(0.0, sigma_dyn)
        rewards[regime].append(-(x**2 + ACTION_COST * action**2))
        next_regime = regime_at(t + 1) if t + 1 < N_STEPS else regime
        mean, cov = identified_belief_predict(mean, cov, action, next_regime)
        previous_y = y
    by_regime = np.array([np.sum(rewards[r]) for r in REGIMES], dtype=float)
    return {
        "total": float(np.sum(by_regime)),
        "regime": by_regime,
        "branch": int(any(abs(a) >= BRANCH_THRESHOLD for a in actions)),
    }


def build_record(seed: int, reps: int) -> dict:
    history = make_history(seed)
    prior = history["identified_prior"]
    truth = rollout_target(
        history["x_start"], prior, np.random.default_rng([seed, 202]),
    )
    record = {
        "truth_total": truth["total"],
        "truth_regime": truth["regime"],
        "branch": truth["branch"],
        "predecision_group": history["predecision_group"],
        "naive_dynamics": {
            "a": history["naive_dynamics"][0],
            "sigma": history["naive_dynamics"][1],
        },
    }
    for kind in ("identified", "naive"):
        rng = np.random.default_rng([seed, 303 if kind == "identified" else 404])
        dynamics = history["naive_dynamics"] if kind == "naive" else (A, SIGMA)
        simulated = [
            rollout_target(
                float(rng.normal(prior[0], math.sqrt(max(prior[1], 1e-12)))),
                prior,
                rng,
                dynamics,
            )
            for _ in range(reps)
        ]
        total = np.array([r["total"] for r in simulated])
        regime = np.stack([r["regime"] for r in simulated])
        record[kind] = {
            "mean_total": float(total.mean()),
            "sd_total": float(total.std(ddof=1)),
            "q05_total": float(np.quantile(total, 0.05)),
            "q95_total": float(np.quantile(total, 0.95)),
            "mean_regime": regime.mean(axis=0),
            "sd_regime": regime.std(axis=0, ddof=1),
            "q05_regime": np.quantile(regime, 0.05, axis=0),
            "q95_regime": np.quantile(regime, 0.95, axis=0),
        }
    return record


def score_blocks(record: dict, kind: str) -> dict:
    est = record[kind]
    return tvc._score_arrays(
        record["truth_total"], est["mean_total"], est["sd_total"],
        est["q05_total"], est["q95_total"], record["truth_regime"],
        est["mean_regime"], est["sd_regime"], est["q05_regime"],
        est["q95_regime"],
    )


def summarize_eval(cal: list[dict], ev: list[dict]) -> dict:
    out = {}
    for kind in ("identified", "naive"):
        cal_scores = [score_blocks(r, kind) for r in cal]
        ev_scores = [score_blocks(r, kind) for r in ev]
        kind_out = {
            "mean_absolute_return_error": float(np.mean([
                abs(r[kind]["mean_total"] - r["truth_total"]) for r in ev
            ])),
            "plugin_normal": {},
            "scores": {},
        }
        truth = np.array([r["truth_total"] for r in ev])
        mean = np.array([r[kind]["mean_total"] for r in ev])
        sd = np.array([r[kind]["sd_total"] for r in ev])
        plugin, _ = tvc._plugin_normal(truth, mean, sd)
        kind_out["plugin_normal"] = plugin
        for score in ("raw", "studentized", "cqr"):
            score_out = {"within_regime": {}, "leave_one_regime_out": {}}
            for k, regime in enumerate(REGIMES):
                cal_s = np.array([s["regime"][score][k] for s in cal_scores])
                ev_s = np.array([s["regime"][score][k] for s in ev_scores])
                scale = (
                    np.array([r[kind]["sd_regime"][k] for r in ev])
                    if score == "studentized" else None
                )
                base = (
                    np.array([
                        r[kind]["q95_regime"][k] - r[kind]["q05_regime"][k]
                        for r in ev
                    ]) if score == "cqr" else None
                )
                covered, widths, q = tvc._conformal(cal_s, ev_s, ALPHA, scale, base)
                score_out["within_regime"][regime] = tvc._summary(covered, widths, [q])
                other = np.concatenate([
                    np.array([s["regime"][score][j] for s in cal_scores])
                    for j in range(len(REGIMES)) if j != k
                ])
                covered, widths, q = tvc._conformal(other, ev_s, ALPHA, scale, base)
                score_out["leave_one_regime_out"][regime] = tvc._summary(covered, widths, [q])
            score_out["full_window"] = {}
            cal_total = np.array([s["total"][score] for s in cal_scores])
            ev_total = np.array([s["total"][score] for s in ev_scores])
            scale = (
                np.array([r[kind]["sd_total"] for r in ev])
                if score == "studentized" else None
            )
            base = (
                np.array([
                    r[kind]["q95_total"] - r[kind]["q05_total"] for r in ev
                ]) if score == "cqr" else None
            )
            covered, widths, q = tvc._conformal(cal_total, ev_total, ALPHA, scale, base)
            score_out["full_window"] = tvc._summary(covered, widths, [q])
            kind_out["scores"][score] = score_out
        out[kind] = kind_out
    return out


def branch_eval(cal: list[dict], ev: list[dict]) -> dict:
    cal_scores = np.array([abs(r["identified"]["mean_total"] - r["truth_total"]) for r in cal])
    ev_scores = np.array([abs(r["identified"]["mean_total"] - r["truth_total"]) for r in ev])
    cal_branch = np.array([r["branch"] for r in cal])
    ev_branch = np.array([r["branch"] for r in ev])
    cal_pre = np.array([r["predecision_group"] for r in cal])
    ev_pre = np.array([r["predecision_group"] for r in ev])
    q_marginal = conformal_q(cal_scores)
    q_pre = {
        int(g): conformal_q(cal_scores[cal_pre == g])
        for g in np.unique(cal_pre)
    }
    q_branch = {
        int(b): conformal_q(cal_scores[cal_branch == b])
        for b in np.unique(cal_branch)
    }
    q_union = max(q_branch.values())
    out = {
        "score": "identified_raw",
        "cal_branch_count": int(np.sum(cal_branch)),
        "test_branch_count": int(np.sum(ev_branch)),
        "cal_branch_fraction": float(np.mean(cal_branch)),
        "test_branch_fraction": float(np.mean(ev_branch)),
        "thresholds": {
            "marginal": q_marginal,
            "predecision": {str(k): v for k, v in q_pre.items()},
            "branch": {str(k): v for k, v in q_branch.items()},
            "union": q_union,
        },
        "rules": {},
    }
    for rule in ("marginal", "predecision", "branch_union"):
        if rule == "marginal":
            q = np.full(len(ev), q_marginal)
        elif rule == "predecision":
            q = np.array([q_pre[int(g)] for g in ev_pre])
        else:
            q = np.full(len(ev), q_union)
        covered = ev_scores <= q
        widths = 2.0 * q
        rule_out = tvc._summary(covered, widths, [])
        rule_out["per_branch"] = {
            str(b): tvc._summary(covered[ev_branch == b], widths[ev_branch == b], [])
            for b in np.unique(ev_branch)
        }
        out["rules"][rule] = rule_out
    return out


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cal-seeds", type=int, default=len(CAL_SEEDS))
    parser.add_argument("--eval-seeds", type=int, default=len(EVAL_SEEDS))
    parser.add_argument("--reps", type=int, default=64)
    parser.add_argument("--out", type=Path, default=OUT_JSON)
    args = parser.parse_args()
    if args.cal_seeds < 1 or args.eval_seeds < 1 or args.reps < 2:
        raise SystemExit("seed counts must be positive and reps must be at least two")
    cal_seeds = CAL_SEEDS[: args.cal_seeds]
    eval_seeds = EVAL_SEEDS[: args.eval_seeds]
    if set(cal_seeds) & set(eval_seeds):
        raise SystemExit("calibration and evaluation seeds must be disjoint")
    cal = [build_record(seed, args.reps) for seed in cal_seeds]
    ev = [build_record(seed, args.reps) for seed in eval_seeds]
    result = {
        "config": {
            "n_steps": N_STEPS,
            "burn_in": BURN_IN,
            "cal_seeds": [cal_seeds[0], cal_seeds[-1]],
            "eval_seeds": [eval_seeds[0], eval_seeds[-1]],
            "reps": args.reps,
            "alpha": ALPHA,
            "regimes": REGIMES,
            "regime_schedule": {
                "degraded": [16, 31], "outage": [32, 39], "normal": "all other steps",
            },
            "target_action_policy": "clip(-0.70 * identified belief mean, -1, 1); the same target-action rule and identified-belief filter are used by truth and both predictive models, but action realizations follow their respective observation histories",
            "naive_dynamics_estimator": "per-path least-squares AR(1) and residual sigma from burn-in observations/actions, used only for the fitted-transition rollout; naive is retained as the internal JSON key",
            "comparison_scope": "shared identified-belief target-action rule/filter and known B=0.35; only the autonomous rollout coefficient and residual scale differ (known A/SIGMA versus fitted AR(1)/residual scale), not the observation filter or target policy",
            "predecision_rule": "three groups from sign and magnitude of the last burn-in observation: y<0, 0<=y<1, y>=1",
            "stream_keys": {
                "burn_in": "[seed,101]", "truth": "[seed,202]",
                "identified_mc": "[seed,303]", "naive_mc": "[seed,404]",
            },
            "parameters": {
                "A": A, "B": B, "sigma": SIGMA,
                "action_gain": ACTION_GAIN, "action_cost": ACTION_COST,
                "logging_gain": LOGGING_GAIN, "obs_sd": OBS_SD,
                "degraded_phi": DEGRADED_PHI, "degraded_sd": DEGRADED_SD,
                "outage_phi": OUTAGE_PHI, "outage_sd": OUTAGE_SD,
                "branch_threshold": BRANCH_THRESHOLD,
            },
        },
        "models": summarize_eval(cal, ev),
        "branch": branch_eval(cal, ev),
        "invariants": {
            "disjoint_seed_sets": not bool(set(cal_seeds) & set(eval_seeds)),
            "latent_start_usage": "history x_start is passed only to the truth rollout; predictive starts are sampled from the shared identified-belief prior",
            "estimator_inputs": "identified uses known A/B/SIGMA and observation-model parameters; fitted-transition knows B and fits only the autonomous rollout coefficient and residual scale from burn-in observations/actions",
            "branch_label_used_for": "calibration-side branch thresholds and test evaluation only",
            "n_cal_paths": len(cal),
            "n_eval_paths": len(ev),
        },
        "limits": [
            "Both predictors know B=0.35; identified-transition also uses known A/SIGMA and observation-model parameters, while fitted-transition estimates only the autonomous rollout coefficient and residual scale from burn-in data.",
            "Both predictive models share the identified-belief target-action rule and filter; this is not an observation-filter or alternative-policy comparison.",
            "Return prediction MAE is a descriptive point estimate without paired uncertainty; no uniform model ranking is claimed.",
            "Coverage is marginal over independent simulated paths; finite cells are reported with their counts and standard errors.",
            "The branch-union rule is sufficient, not optimal; its width is reported alongside coverage.",
        ],
    }
    assert result["invariants"]["disjoint_seed_sets"]
    assert 0 < result["branch"]["cal_branch_count"] < len(cal)
    assert 0 < result["branch"]["test_branch_count"] < len(ev)
    for model in result["models"].values():
        assert math.isfinite(model["mean_absolute_return_error"])
        for score in model["scores"].values():
            for protocol in ("within_regime", "leave_one_regime_out"):
                for cell in score[protocol].values():
                    assert 0.0 <= cell["coverage"] <= 1.0
                    assert not math.isnan(cell["mean_width"]) and cell["mean_width"] >= 0.0
    result["invariants"]["valid_coverage_and_width"] = True
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(result, indent=2), encoding="utf-8")
    print(json.dumps({
        "out": str(args.out),
        "identified_mean_absolute_return_error": result["models"]["identified"]["mean_absolute_return_error"],
        "naive_mean_absolute_return_error": result["models"]["naive"]["mean_absolute_return_error"],
        "branch": result["branch"]["rules"],
    }, indent=2))


if __name__ == "__main__":
    main()
